#!/usr/bin/env python3
"""Write docs/reports/timeline_m1.md: every timeline event and itinerary step in time order,
plus every content entry marked "verify": true (events, steps, rumours, lore cards, items).

Usage: .venv/bin/python tools/content/report_timeline.py [--root DIR] [--out FILE]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
DEFAULT_ROOT = REPO / "game" / "content"
DEFAULT_OUT = REPO / "docs" / "reports" / "timeline_m1.md"


def load(root: Path, pattern: str) -> list[tuple[str, Any]]:
    return [(p.relative_to(root).as_posix(), json.loads(p.read_text())) for p in sorted(root.glob(pattern))]


def collect(root: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for file, evs in load(root, "timeline/events/*.json"):
        for e in evs:
            rows.append({
                "at": e["at"], "id": e["id"], "kind": e["type"], "actors": e.get("actors", []),
                "where": e.get("location", ""), "waits": bool(e.get("waits_for_player")),
                "verify": bool(e.get("verify")), "file": file, "deps": e.get("depends_on", []),
                "window_end": e.get("window_end"), "area": e.get("trigger_area"),
            })
    for file, it in load(root, "timeline/itineraries/*.json"):
        who = it["character"]
        for s in it["steps"]:
            where = s.get("at_poi") or f"{s.get('from', '?')} -> {s.get('to', '?')}"
            note = ("abstract " if s.get("abstract") else "") + s["action"]
            rows.append({
                "at": s["at"], "id": s["id"], "kind": note, "actors": [who] + s.get("companions", []),
                "where": where, "waits": False, "verify": bool(s.get("verify") or it.get("verify")),
                "file": file, "deps": s.get("depends_on", []), "window_end": None, "area": None,
            })
    rows.sort(key=lambda r: (r["at"] if "T" in r["at"] else r["at"] + "T00:00", r["file"], r["id"]))
    return rows


def verify_entries(root: Path) -> list[tuple[str, str, str]]:
    out: list[tuple[str, str, str]] = []
    for file, data in load(root, "rumours/*.json"):
        out += [(file, r["id"], r["text"]) for r in data if r.get("verify")]
    for file, data in load(root, "lore_cards/characters/*.json"):
        if data.get("verify"):
            out.append((file, data["id"], "whole card"))
        out += [(file, f"{data['id']}.{k['id']}", k["fact"]) for k in data.get("knowledge", []) if k.get("verify")]
    for file, data in load(root, "items/*.json"):
        out += [(file, i["id"], i["name"]) for i in data if i.get("verify")]
    return out


def render(root: Path) -> str:
    rows = collect(root)
    L = ["# M1 timeline report (T.A. 3018-09-20 to 3018-10-06)", "",
         "Generated by `tools/content/report_timeline.py`; do not edit by hand.",
         "Times are nominal (mode A). In mode B, steps that depend on a `waits` event shift by its delay.", "",
         f"{len(rows)} entries. `V` = marked verify. `W` = waits_for_player.", "",
         "| Time | Id | Kind | Actors | Location | W | V | Depends on |",
         "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        w = "W" if r["waits"] else ""
        L.append(f"| {r['at'].replace('T', ' ')} | `{r['id']}` | {r['kind']} | {', '.join(r['actors'])} | "
                 f"{r['where']} | {w} | {'V' if r['verify'] else ''} | {', '.join(r['deps'])} |")
    waiters = [r for r in rows if r["waits"]]
    if waiters:
        L += ["", "## Events that wait for the player (mode B)", ""]
        for r in waiters:
            L.append(f"- `{r['id']}` at {r['at']}: trigger area {json.dumps(r['area'])}, window ends {r['window_end']}")
    L += ["", "## Entries marked verify (check against Appendix B)", "", "### Timeline events and itinerary steps", ""]
    for r in rows:
        if r["verify"]:
            L.append(f"- {r['at'].replace('T', ' ')} `{r['id']}` ({r['file']}): {', '.join(r['actors'])} @ {r['where']}")
    L += ["", "### Rumours, lore cards, items", ""]
    for file, ident, text in verify_entries(root):
        L.append(f"- `{ident}` ({file}): {text}")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(args.root))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
